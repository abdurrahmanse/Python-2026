# arguments and parameters
def greet(name):
    print(f"Hello, {name}!")


greet("Alice")
greet("Bob")


def add(a, b):
    return a + b


result = add(5, 3)
print(result)  # Output: 8


def multiply(x, y):
    return x * y


product = multiply(4, 6)
print(product)  # Output: 24


def power(base, exponent):
    return base ** exponent


result = power(2, 3)
print(result)  # Output: 8
