# variables and data types

x = 5
y = "Hello, World!"
print(x)
print(y)

# data types
a = 10          # integer
b = 3.14        # float
c = "Python"     # string
d = True         # boolean
print(type(a))
print(type(b))

print(type(c))
print(type(d))
# type conversion
num_str = "100"
num_int = int(num_str)  # convert string to integer
print(num_int)
num_float = float(num_str)  # convert string to float
print(num_float)
str_num = str(num_int)  # convert integer to string
print(str_num)
# multiple assignment
x, y, z = 1, 2, 3
print(x, y, z)
# constants (by convention, use uppercase variable names)
PI = 3.14159
GRAVITY = 9.81
print(PI)
print(GRAVITY)
