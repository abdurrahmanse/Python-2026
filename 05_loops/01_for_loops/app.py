# For Loops in Python

cities = ["New York", "Los Angeles", "Chicago", "Houston", "Phoenix"]
# Using a for loop to iterate through the list of cities
for city in cities:
    print(city)
# Using a for loop with the range function to print numbers from 0 to 4
for i in range(5):
    print(i)
# Using a for loop to iterate through a string
name = "Python"
for letter in name:
    print(letter)
# Using a for loop to iterate through a dictionary
person = {"name": "Alice", "age": 30, "city": "New York"}
for key in person:
    print(f"{key}: {person[key]}")
