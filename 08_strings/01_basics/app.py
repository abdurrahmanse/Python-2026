# basic string examples:

name = "Alice"
print(name)

# Concatenation
greeting = "Hello, " + name + "!"
print(greeting)

# String formatting
age = 30
formatted_string = f"{name} is {age} years old."
print(formatted_string)

# String methods
upper_case_name = name.upper()
print(upper_case_name)

# String slicing
first_letter = name[0]
print(first_letter)

last_letter = name[-1]
print(last_letter)

